"""Generate galahad.urdf from docs/joint_map.json (the Blender rig).

    python tools/gen_urdf.py

Link frames, joint origins and link bounding boxes come straight from the Blender
armature, so the URDF and the CAD share one source of truth. Visual shapes are
approximating boxes/cylinders — the high-fidelity geometry lives in
blender/galahad.glb. Masses are engineering estimates, not measurements.
"""
import json
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "docs", "joint_map.json")
OUT = os.path.join(ROOT, "ros2_ws", "src", "galahad_description", "urdf", "galahad.urdf")

# Joint limits: design targets from the engineering brief, to be replaced by
# measured values after bench characterisation. degrees.
LIMITS = {
    "waist_yaw": (-90, 90, 20),
    "waist_pitch": (-20, 20, 15),
    "head_pan": (-80, 80, 60),
    "head_tilt": (-25, 35, 60),
    "shoulder_yaw_L": (-80, 80, 40),
    "shoulder_yaw_R": (-80, 80, 40),
    "shoulder_pitch_L": (-100, 95, 40),
    "shoulder_pitch_R": (-100, 95, 40),
    "elbow_L": (-120, 90, 40),
    "elbow_R": (-120, 90, 40),
    "wrist_L": (-90, 90, 60),
    "wrist_R": (-90, 90, 60),
    "gripper_L": (0, 55, 40),
    "gripper_R": (0, 55, 40),
}

# Estimated masses (kg) — split of a 1.25 kg target, UNVERIFIED.
MASS = {
    "base_link": 0.46,
    "waist_yaw": 0.045,
    "waist_pitch": 0.035,
    "torso": 0.30,
    "head_pan": 0.02,
    "head_tilt": 0.085,
    "shoulder_pitch_L": 0.055,
    "elbow_L": 0.045,
    "wrist_L": 0.03,
    "gripper_L": 0.035,
    "shoulder_pitch_R": 0.055,
    "elbow_R": 0.045,
    "wrist_R": 0.03,
    "gripper_R": 0.035,
}
# Joints that are structural (no actuator of their own) but need a link.
FIXED = {"shoulder_yaw_L": "shoulder_pitch_L", "shoulder_yaw_R": "shoulder_pitch_R"}

AXIS = {
    "waist_yaw": "0 0 1",
    "waist_pitch": "1 0 0",
    "head_pan": "0 0 1",
    "head_tilt": "1 0 0",
    "shoulder_yaw_L": "0 0 1",
    "shoulder_yaw_R": "0 0 1",
    "shoulder_pitch_L": "0 1 0",
    "shoulder_pitch_R": "0 1 0",
    "elbow_L": "0 1 0",
    "elbow_R": "0 1 0",
    "wrist_L": "0 1 0",
    "wrist_R": "0 1 0",
    "gripper_L": "0 1 0",
    "gripper_R": "0 1 0",
}


def box_inertia(mass, sx, sy, sz):
    sx, sy, sz = sx / 1000.0, sy / 1000.0, sz / 1000.0
    return (mass / 12.0 * (sy ** 2 + sz ** 2),
            mass / 12.0 * (sx ** 2 + sz ** 2),
            mass / 12.0 * (sx ** 2 + sy ** 2))


def mm(v):
    return v / 1000.0


def main():
    data = json.load(open(SRC))
    joints = {j["name"]: j for j in data["joints"]}
    parts = data["parts"]

    # merge the two shoulder-yaw links into their pitch link (rig convenience)
    # (kept explicit: shoulder yaw is a driven joint in its own right)

    order = ["base_link", "waist_yaw", "waist_pitch", "torso", "head_pan", "head_tilt",
             "shoulder_yaw_L", "shoulder_pitch_L", "elbow_L", "wrist_L", "gripper_L",
             "shoulder_yaw_R", "shoulder_pitch_R", "elbow_R", "wrist_R", "gripper_R"]

    lines = ['<?xml version="1.0"?>',
             '<!-- Galahad companion robot - generated by tools/gen_urdf.py -->',
             '<!-- Link frames and joint origins come from blender/galahad.blend (mm -> m).',
             '     Masses and limits are engineering estimates, not measurements. -->',
             '<robot name="galahad">']

    for name in order:
        j = joints[name]
        bb = j.get("bbox_mm", {"size": [60, 60, 40], "min": [-30, -30, -20], "max": [30, 30, 20]})
        sx, sy, sz = bb["size"]
        center = [(bb["min"][i] + bb["max"][i]) / 2.0 - j["head_mm"][i] for i in range(3)]
        mass = MASS.get(name, 0.04)
        ixx, iyy, izz = box_inertia(mass, sx, sy, sz)
        hx, hy, hz = sx / 2000.0, sy / 2000.0, sz / 2000.0
        lines.append(f'  <link name="{name}">')
        lines.append('    <visual>')
        lines.append(f'      <origin xyz="{mm(center[0]):.4f} {mm(center[1]):.4f} {mm(center[2]):.4f}" rpy="0 0 0"/>')
        lines.append(f'      <geometry><box size="{hx * 2:.4f} {hy * 2:.4f} {hz * 2:.4f}"/></geometry>')
        lines.append('      <material name="ivory"><color rgba="0.93 0.89 0.82 1"/></material>')
        lines.append('    </visual>')
        lines.append('    <collision>')
        lines.append(f'      <origin xyz="{mm(center[0]):.4f} {mm(center[1]):.4f} {mm(center[2]):.4f}" rpy="0 0 0"/>')
        lines.append(f'      <geometry><box size="{hx * 2:.4f} {hy * 2:.4f} {hz * 2:.4f}"/></geometry>')
        lines.append('    </collision>')
        lines.append('    <inertial>')
        lines.append(f'      <origin xyz="{mm(center[0]):.4f} {mm(center[1]):.4f} {mm(center[2]):.4f}" rpy="0 0 0"/>')
        lines.append(f'      <mass value="{mass:.4f}"/>')
        lines.append(f'      <inertia ixx="{ixx:.6f}" ixy="0" ixz="0" iyy="{iyy:.6f}" iyz="0" izz="{izz:.6f}"/>')
        lines.append('    </inertial>')
        lines.append('  </link>')

    for name in order:
        if name == "base_link":
            continue
        j = joints[name]
        parent = j["parent"]
        ph = joints[parent]["head_mm"]
        origin = [j["head_mm"][i] - ph[i] for i in range(3)]
        lim = LIMITS.get(name)
        jtype = "fixed" if name == "torso" else "revolute"
        lines.append(f'  <joint name="{name}_joint" type="{jtype}">')
        lines.append(f'    <parent link="{parent}"/>')
        lines.append(f'    <child link="{name}"/>')
        lines.append(f'    <origin xyz="{mm(origin[0]):.4f} {mm(origin[1]):.4f} {mm(origin[2]):.4f}" rpy="0 0 0"/>')
        if jtype == "revolute":
            lines.append(f'    <axis xyz="{AXIS.get(name, "0 0 1")}"/>')
            if lim:
                lines.append(f'    <limit lower="{math.radians(lim[0]):.4f}" upper="{math.radians(lim[1]):.4f}" '
                             f'effort="0.93" velocity="{math.radians(lim[2]):.4f}"/>')
            else:
                lines.append('    <limit lower="-3.14" upper="3.14" effort="0.52" velocity="1.0"/>')
        lines.append('  </joint>')

    # treads as continuous wheel joints for diff_drive_controller
    for side in ("L", "R"):
        lines.append(f'  <joint name="tread_{side}_joint" type="continuous">')
        lines.append('    <parent link="base_link"/>')
        lines.append(f'    <child link="tread_{side}"/>')
        lines.append(f'    <origin xyz="{"-0.055" if side == "L" else "0.055"} 0 0.025" rpy="0 0 0"/>')
        lines.append('    <axis xyz="0 1 0"/>')
        lines.append('    <limit effort="0.16" velocity="34.6"/>')
        lines.append('  </joint>')
        lines.append(f'  <link name="tread_{side}">')
        lines.append('    <visual><geometry><cylinder radius="0.0195" length="0.0146"/></geometry>'
                     '<material name="rubber"><color rgba="0.08 0.08 0.09 1"/></material></visual>')
        lines.append('    <collision><geometry><cylinder radius="0.0195" length="0.0146"/></geometry></collision>')
        lines.append('    <inertial><mass value="0.02"/><inertia ixx="0.0000019" ixy="0" ixz="0" '
                     'iyy="0.0000019" iyz="0" izz="0.0000019"/></inertial>')
        lines.append('  </link>')

    lines.append('</robot>')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("wrote", OUT, len(lines), "lines")


if __name__ == "__main__":
    main()
